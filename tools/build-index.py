LANG_NAMES = {"de": "German", "en": "English"}


PERSONAL = """<h1>Personal courses</h1>
<p class="lede">Courses with "audience": "personal" in course.json. They are not on the landing page or in the updates, and search engines are asked to skip them. This page is not linked from anywhere, but it is public.</p>
{sections}
{updates}"""


def write_page(hub, name, title, main, noindex=False):
    extra = '\n<meta name="robots" content="noindex">' if noindex else ""
    page = FRAME.replace("{title}", title).replace("{head_extra}", extra).replace("{main}", main)
    (hub / name).write_text(page, encoding="utf-8")


def load_courses(hub):
    courses = []
    for meta in sorted(hub.rglob("course.json")):
        rel = meta.parent.relative_to(hub)
        if not rel.parts or rel.parts[0] in SKIP:
            continue
        data = json.loads(meta.read_text(encoding="utf-8"))
        data["_href"] = rel.as_posix() + "/"
        try:
            data["_changes"] = changes.load(meta.parent)
        except changes.ChangesError as e:
            sys.exit(f"CHANGES.md: {e}")
        courses.append(data)
    return courses


def card(c):
    code = str(c.get("language", "")).lower()
    name = LANG_NAMES.get(code, code.upper())
    badge = (f'<span class="badge" title="In {html.escape(name)}">{html.escape(code.upper())}</span>'
             if code else "")
    return (
        f'<li class="card"><a href="{html.escape(c["_href"])}" hreflang="{html.escape(code)}">'
        f'<span class="title">{html.escape(c["title"])}{badge}</span>'
        f'<span class="desc">{html.escape(c.get("description", ""))}</span>{updated(c)}</a></li>'
    )


def updated(c):
    if not c["_changes"]:
        return ""
    day = c["_changes"][0][0]
    return (f'<span class="updated" data-updated="{day.isoformat()}">Updated '
            f'<time datetime="{day.isoformat()}">{changes.fmt_date(day, "en")}</time></span>')


def rows(courses):
    """(date, course, items) for every CHANGES.md entry, newest first."""
    out = [(day, c, items) for c in courses for day, items in c["_changes"]]
    out.sort(key=lambda r: (r[0], r[1]["title"].lower()), reverse=True)
    return out


def recent(courses):
    """Landing page: the newest entries, one line each, and a link to updates.html."""
    latest = rows(courses)[:RECENT]
    if not latest:
        return ""
    out = []
    for day, c, items in latest:
        lang = changes.lang_of(c)
        kind, body = items[0]
        tag = (f'<span class="change-kind change-{kind}">{changes.KIND_LABEL[lang][kind]}</span> '
               if kind else "")
        text = changes.plain(body)
        if len(text) > 80:
            text = text[:78].rsplit(" ", 1)[0] + " …"
        more = f' <span class="more">+{len(items) - 1} more</span>' if len(items) > 1 else ""
        out.append(f'<li><time datetime="{day.isoformat()}">{changes.fmt_date(day, "en", short=True)}</time>'
                   f'<a class="course" href="{html.escape(c["_href"])}changes.html">{html.escape(c["title"])}</a>'
                   f'<span class="what">{tag}{html.escape(text)}{more}</span></li>')
    return ('<section class="recent" aria-labelledby="recent-h">\n'
            '<div class="section-head"><h2 id="recent-h">Recent updates</h2>'
            '<a href="updates.html">All updates &rarr;</a></div>\n'
            '<ul class="recent-list">\n' + "\n".join(out) + '\n</ul>\n</section>')


def all_updates(courses):
    """updates.html: every entry of every course, newest first."""
    out = []
    for day, c, items in rows(courses):
        lang = changes.lang_of(c)
        lis = "\n".join(changes.item_html(k, b, lang, c["_href"]) for k, b in items)
        out.append(f'<li><time datetime="{day.isoformat()}">{changes.fmt_date(day, "en")}</time> '
                   f'<a class="course" href="{html.escape(c["_href"])}changes.html">'
                   f'{html.escape(c["title"])}</a>\n<ul>\n{lis}\n</ul></li>')
    body = ('<ul class="updates">\n' + "\n".join(out) + '\n</ul>') if out else "<p>No updates yet.</p>"
    return ('<h1>All updates</h1>\n<p class="lede">Changes to all courses, newest first.</p>\n'
            + body + '\n<p><a href="index.html">&larr; All courses</a></p>')


def is_personal(c):
    return str(c.get("audience", "")).lower() == "personal"


def card_sections(courses):
    topics = {}
    for c in courses:
        topics.setdefault(c.get("topic") or "Other", []).append(c)
    sections = []
    for topic in sorted(topics, key=str.lower):
        items = "\n".join(card(c) for c in sorted(topics[topic], key=lambda c: c["title"].lower()))
        sections.append(f'<h2>{html.escape(topic)}</h2>\n<ul class="cards">\n{items}\n</ul>')
    return "\n".join(sections) or "<p>No courses published yet.</p>"


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    hub = pathlib.Path(sys.argv[1]).resolve()
    everything = load_courses(hub)
    courses = [c for c in everything if not is_personal(c)]
    personal = [c for c in everything if is_personal(c)]

    home = HOME.replace("{sections}", card_sections(courses)).replace("{recent}", recent(courses))
    write_page(hub, "index.html", "Learn: all courses", home)
    write_page(hub, "updates.html", "Learn: all updates", all_updates(courses))
    write_page(hub, "about.html", "Learn: about these courses", ABOUT)
    if personal:
        updates = all_updates(personal).replace("<h1>All updates</h1>", "<h2>Updates</h2>", 1)
        updates = updates.replace('<p class="lede">Changes to all courses, newest first.</p>\n', "", 1)
        page = PERSONAL.replace("{sections}", card_sections(personal)).replace("{updates}", updates)
        write_page(hub, "personal.html", "Learn: personal courses", page, noindex=True)
    else:
        (hub / "personal.html").unlink(missing_ok=True)
    print(f"index.html, updates.html, about.html: {len(courses)} courses; "
          f"personal.html: {len(personal)}")


if __name__ == "__main__":
    main()
