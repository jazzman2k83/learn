#!/usr/bin/env python3
"""Write the hub's landing page (index.html) from every published course.json.

Usage: build-index.py <hub-dir>

Each course folder in the hub holds a copy of its course.json (see README.md).
Courses are grouped by "topic" and sorted by title. Only the standard library is used.
"""
import html
import json
import pathlib
import sys

SKIP = {"tools", "assets", ".git", ".github"}

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Learn: all courses</title>
<script src="assets/hub.js"></script>
<link rel="stylesheet" href="assets/hub.css">
</head>
<body>
<!-- Generated by tools/build-index.py. Do not edit; your changes will be overwritten. -->
<header class="topbar"><a class="brand" href="index.html">Learn</a><button type="button" class="theme-toggle" data-theme-toggle>&#9790; Dark</button></header>
<main>
<h1>Short interactive courses</h1>
<p class="lede">Each course runs in the browser, with no installation and no account. Pick one and work through its lessons in order.</p>
{sections}
<p class="small">{count} courses. DE = German, EN = English.</p>
</main>
</body>
</html>
"""


def load_courses(hub):
    courses = []
    for meta in sorted(hub.rglob("course.json")):
        rel = meta.parent.relative_to(hub)
        if not rel.parts or rel.parts[0] in SKIP:
            continue
        data = json.loads(meta.read_text(encoding="utf-8"))
        data["_href"] = rel.as_posix() + "/"
        courses.append(data)
    return courses


def card(c):
    lang = html.escape(str(c.get("language", "")).upper())
    badge = f'<span class="badge">{lang}</span>' if lang else ""
    return (
        f'<li class="card"><a href="{html.escape(c["_href"])}" hreflang="{html.escape(str(c.get("language", "")))}">'
        f'<span class="title">{html.escape(c["title"])}{badge}</span>'
        f'<span class="desc">{html.escape(c.get("description", ""))}</span></a></li>'
    )


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    hub = pathlib.Path(sys.argv[1]).resolve()
    courses = load_courses(hub)

    topics = {}
    for c in courses:
        topics.setdefault(c.get("topic") or "Other", []).append(c)

    sections = []
    for topic in sorted(topics, key=str.lower):
        items = "\n".join(card(c) for c in sorted(topics[topic], key=lambda c: c["title"].lower()))
        sections.append(f'<h2>{html.escape(topic)}</h2>\n<ul class="cards">\n{items}\n</ul>')
    if not sections:
        sections.append("<p>No courses published yet.</p>")

    page = PAGE.replace("{sections}", "\n".join(sections)).replace("{count}", str(len(courses)))
    (hub / "index.html").write_text(page, encoding="utf-8")
    print(f"index.html: {len(courses)} courses")


if __name__ == "__main__":
    main()
